/* =========================================================
   账号服务配置 — v1.0.0
   ---------------------------------------------------------
   站点是纯静态的（GitHub Pages），没有自己的服务器，
   所以账号交给托管服务，浏览器直接和它对话。

   默认用 Supabase：免费额度对个人站绰绰有余，
   自带邮箱密码 / 魔法链接 / GitHub 登录，还有 Postgres 数据库，
   以后想把收藏同步到云端可以直接用它的表。

   填上这两个值就接通了：
     url     → Supabase 控制台 → 项目设置 → API → Project URL
     anonKey → 同页 → Project Publishable key / anon public key

   注意：anon 公钥本来就是设计给前端用的，可以公开写在这里；
   service_role 密钥绝对不要进前端，也不要提交到仓库。
   ========================================================= */
window.SITE_AUTH = {
  provider: 'supabase',
  url: '',
  anonKey: '',

  // 两个值都没填 → 自动退回「本地模式」：
  // 账号只存在这台设备的 localStorage 里，纯粹是个能跑通的流程演示。
  // 填上 url + anonKey 后自动切到真正的云端账号。
};
